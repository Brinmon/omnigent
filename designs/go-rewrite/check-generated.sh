#!/usr/bin/env bash
# Regenerate the oapi-codegen output and verify it matches the checked-in files.
#
# The generated interface is a compile-time guard, which only holds while it
# matches openapi.json. A stale generation compiles fine and guards the wrong
# contract, so this compares a fresh run against the committed files.
#
# Usage:
#   bash designs/go-rewrite/check-generated.sh          # verify
#   bash designs/go-rewrite/check-generated.sh --write  # regenerate in place
#
# The A-group contract run calls this first, so a stale generation fails the
# gate rather than passing it.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT" || exit 1

API_DIR="$REPO_ROOT/go/internal/api"
SPEC="$REPO_ROOT/openapi.json"
WRITE=false
[[ "${1:-}" == "--write" ]] && WRITE=true

if ! command -v oapi-codegen > /dev/null 2>&1; then
  printf 'SKIP: oapi-codegen not on PATH\n'
  printf '      install with: go install github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@latest\n'
  exit 0
fi

# The scratch dir lives inside the repo because oapi-codegen resolves
# ``output:`` relative to the config file and rejects some absolute POSIX paths
# on Windows; a repo-relative path works on every platform.
TMP="$REPO_ROOT/go/.generated-check"
rm -rf "$TMP"
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

# Regenerate both files into a scratch dir, then compare.
status=0
for pair in "oapi-codegen.yaml:types.gen.go" "oapi-server.yaml:server.gen.go"; do
  config="${pair%%:*}"
  target="${pair##*:}"

  # A generated file's header names the generator version, which changes with
  # the tool; compare everything else so a version bump is not a false alarm.
  # Output paths are relative to the config file, so the config sits beside the
  # file it produces.
  sed "s|^output: .*|output: $target|" "$API_DIR/$config" > "$TMP/$config"
  if ! ( cd "$TMP" && oapi-codegen -config "$TMP/$config" "$SPEC" ) > "$TMP/$target.err" 2>&1; then
    printf 'FAIL: regenerating %s failed:\n' "$target"
    cat "$TMP/$target.err"
    status=1
    continue
  fi

  if [[ ! -f "$API_DIR/$target" ]]; then
    printf 'FAIL: %s is missing; run with --write\n' "$target"
    status=1
    continue
  fi

  if ! diff -q <(grep -v '^// Code generated by' "$API_DIR/$target") \
               <(grep -v '^// Code generated by' "$TMP/$target") > /dev/null; then
    printf 'FAIL: %s does not match openapi.json\n' "$target"
    diff -u <(grep -v '^// Code generated by' "$API_DIR/$target") \
            <(grep -v '^// Code generated by' "$TMP/$target") | head -40
    if $WRITE; then
      cp "$TMP/$target" "$API_DIR/$target"
      printf '      rewrote %s\n' "$target"
    else
      printf '      regenerate with: bash designs/go-rewrite/check-generated.sh --write\n'
    fi
    status=1
  else
    printf 'OK: %s matches openapi.json\n' "$target"
  fi
done

exit $status
