"""Generate go/internal/db/enumcodes.gen.go from a Python-produced enum dump.

The enum codes are an append-only on-disk contract, so they are transcribed
mechanically rather than retyped: a hand-written table drifts silently the
next time a value is added. Regenerate after changing
``omnigent/db/enum_codecs.py``::

    python designs/go-rewrite/make-reference-db.py          # refresh the dump
    python designs/go-rewrite/gen-enum-codes.py             # then this

A test (``enumcodes_test.go``) parses the dump at run time and fails when the
generated table and the dump disagree, so a forgotten regeneration is caught
by ``go test`` rather than by a misread row in production.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
_DUMP = _REPO_ROOT / "go" / "testdata" / "enum_codes.json"
_OUT = _REPO_ROOT / "go" / "internal" / "db" / "enumcodes.gen.go"

# Go identifier per dump key, plus the column the code belongs to so the
# generated doc comment names where it is stored.
_TABLES = {
    "conversation_kind": ("ConversationKind", "conversations.kind"),
    "item_type": ("ItemType", "conversation_items.type"),
    "item_status": ("ItemStatus", "conversation_items.status"),
    "comment_status": ("CommentStatus", "comments.status"),
    "session_live_status": ("SessionLiveStatus", "omnigent_conversation_metadata.live_status"),
    "account_token_kind": ("AccountTokenKind", "account_tokens.kind"),
    "policy_type": ("PolicyType", "policies.type"),
    "policy_scope": ("PolicyScope", "policies.scope"),
    "device_grant_status": ("DeviceGrantStatus", "device_grants.status"),
    "host_status": ("HostStatus", "hosts.status"),
    "agent_kind": ("AgentKind", "agents.kind"),
    "scheduled_task_state": ("ScheduledTaskState", "scheduled_tasks.state"),
    "scheduled_task_execution_target": (
        "ScheduledTaskExecutionTarget",
        "scheduled_tasks.execution_target",
    ),
    "scheduled_task_session_mode": (
        "ScheduledTaskSessionMode",
        "scheduled_tasks.session_mode",
    ),
    "scheduled_task_run_status": ("ScheduledTaskRunStatus", "scheduled_task_runs.status"),
}

_HEADER = '''\
// Code generated by designs/go-rewrite/gen-enum-codes.py; DO NOT EDIT.

package db

// Enum codes for SMALLINT columns. Codes are STABLE and append-only: never
// renumber or reuse a shipped code, and leave gaps rather than reordering, so
// rows written by an older release keep their meaning. The string names stay
// the contract for entities, the HTTP API, and the web client; the integer
// form never leaves the store row-to-entity boundary.
'''


def _go_string(value: str) -> str:
    return json.dumps(value)


def main() -> int:
    if not _DUMP.is_file():
        raise SystemExit(f"missing {_DUMP}; run make-reference-db.py first")
    tables: dict[str, dict[str, int]] = json.loads(_DUMP.read_text(encoding="utf-8"))

    missing = set(tables) - set(_TABLES)
    if missing:
        raise SystemExit(
            f"no Go name mapping for {sorted(missing)}; add it to _TABLES in {__file__}"
        )
    unused = set(_TABLES) - set(tables)
    if unused:
        raise SystemExit(f"mapping for {sorted(unused)} has no table in the dump")

    parts: list[str] = [_HEADER]
    for key in sorted(tables):
        go_name, column = _TABLES[key]
        codes = tables[key]
        # Sort by code so the generated file reads like the on-disk ordering.
        ordered = sorted(codes.items(), key=lambda kv: kv[1])
        lines = [
            "",
            f"// {go_name} codes for {column}.",
            f"var {go_name} = map[string]int64{{",
        ]
        width = max(len(_go_string(name)) for name, _ in ordered) + 1  # +1 for the colon
        for name, code in ordered:
            key = _go_string(name) + ":"
            lines.append(f"\t{key:<{width}} {code},")
        lines.append("}")
        inv = [
            "",
            f"// {go_name}Name maps a stored code back to its name for {column}.",
            f"var {go_name}Name = map[int64]string{{",
        ]
        iw = max(len(str(code)) for _, code in ordered) + 1  # +1 for the colon
        for name, code in ordered:
            key = f"{code}:"
            inv.append(f"\t{key:<{iw}} {_go_string(name)},")
        inv.append("}")
        parts.append("\n".join(lines + inv))

    parts.append(_encode_helpers(sorted(tables)))
    _OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    total = sum(len(t) for t in tables.values())
    print(f"wrote {_OUT} ({len(tables)} tables, {total} codes)")
    return 0


def _encode_helpers(keys: list[str]) -> str:
    """Emit Encode/Decode helpers bound to each generated table."""
    out = [
        "",
        "// EncodeName maps an enum name to its stored code.",
        "//",
        "// An unknown name is an error rather than a zero code so a caller cannot",
        "// persist a value the reader will not understand.",
        "func EncodeName(table map[string]int64, field, name string) (int64, error) {",
        "\tcode, ok := table[name]",
        "\tif !ok {",
        '\t\treturn 0, &UnknownEnumValueError{Field: field, Name: name}',
        "\t}",
        "\treturn code, nil",
        "}",
        "",
        "// DecodeName maps a stored code back to its enum name.",
        "func DecodeName(inverse map[int64]string, field string, code int64) (string, error) {",
        "\tname, ok := inverse[code]",
        "\tif !ok {",
        '\t\treturn "", &UnknownEnumCodeError{Field: field, Code: code}',
        "\t}",
        "\treturn name, nil",
        "}",
        "",
        "// UnknownEnumValueError reports a name with no stable code.",
        "type UnknownEnumValueError struct {",
        "\tField string",
        "\tName  string",
        "}",
        "",
        "func (e *UnknownEnumValueError) Error() string {",
        '\treturn "unknown " + e.Field + " value: " + e.Name',
        "}",
        "",
        "// UnknownEnumCodeError reports a stored code with no known name.",
        "type UnknownEnumCodeError struct {",
        "\tField string",
        "\tCode  int64",
        "}",
        "",
        "func (e *UnknownEnumCodeError) Error() string {",
        '\treturn "unknown " + e.Field + " code"',
        "}",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    sys.exit(main())
