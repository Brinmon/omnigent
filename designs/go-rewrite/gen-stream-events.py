#!/usr/bin/env python
"""Generate go/internal/event/streamevents.gen.go from openapi.json.

A4: the SSE event union is the contract between server and the reused web
client, which switches on the discriminator value. Python, TypeScript, and the
Go rewrite all have to agree on the same 56 names, so the Go set is
transcribed from the published document instead of retyped.

Regenerate after changing ``omnigent/server/schemas.py``::

    python designs/go-rewrite/gen-stream-events.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SPEC = _REPO_ROOT / "openapi.json"
_OUT = _REPO_ROOT / "go" / "internal" / "event" / "streamevents.gen.go"

_HEADER = '''\
// Code generated by designs/go-rewrite/gen-stream-events.py; DO NOT EDIT.

package event
'''


def main() -> int:
    if not _SPEC.is_file():
        raise SystemExit(f"missing {_SPEC}")

    spec = json.loads(_SPEC.read_text(encoding="utf-8"))
    union = spec["components"]["schemas"]["ServerStreamEvent"]
    mapping: dict[str, str] = union["discriminator"]["mapping"]

    one_of = union.get("oneOf") or []
    refs = {
        entry["$ref"].rsplit("/", 1)[-1] for entry in one_of if "$ref" in entry
    }
    mapped = {target.rsplit("/", 1)[-1] for target in mapping.values()}
    if refs != mapped:
        raise SystemExit(
            "openapi.json is internally inconsistent: oneOf and discriminator "
            f"mapping disagree (only in oneOf: {sorted(refs - mapped)}, "
            f"only in mapping: {sorted(mapped - refs)})"
        )

    names = sorted(mapping)
    parts = [
        _HEADER,
        "",
        "// StreamEventTypes is every value the ServerStreamEvent discriminator can",
        "// take, sorted.",
        "//",
        "// The web client keys its reducer off these strings, so the set is a wire",
        "// contract: a missing value means a UI state that can never render, and an",
        "// unknown one means an event the client silently drops.",
        "var StreamEventTypes = []string{",
    ]
    for name in names:
        parts.append(f"\t{json.dumps(name)},")
    parts.append("}")
    parts.append("")
    parts.append("// StreamEventSchema maps each discriminator value to its schema name,")
    parts.append("// so a test can assert the payload shape behind each type.")
    parts.append("var StreamEventSchema = map[string]string{")
    width = max(len(json.dumps(name)) for name in names) + 1
    for name in names:
        key = json.dumps(name) + ":"
        parts.append(f"\t{key:<{width}} {json.dumps(mapping[name].rsplit('/', 1)[-1])},")
    parts.append("}")
    parts.append("")
    parts.append(f"// StreamEventCount is the number of discriminator values ({len(names)}).")
    parts.append(f"const StreamEventCount = {len(names)}")

    _OUT.parent.mkdir(parents=True, exist_ok=True)
    _OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {_OUT} ({len(names)} event types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
